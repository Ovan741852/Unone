import assert from 'node:assert/strict';
import {TownCamera} from '../viewer/camera.js';
const near=(a,b)=>assert.ok(Math.abs(a-b)<.01,`${a} should be near ${b}`);
const camera=new TownCamera();
assert.equal(camera.followId,null);
const oldView=camera.view();camera.rotate(120,20);
assert.notEqual(camera.view().position.x,oldView.position.x);
camera.rotate(0,10000);assert.equal(camera.pitch,1.35);
camera.rotate(0,-10000);assert.equal(camera.pitch,.35);
camera.yaw=0;camera.x=0;camera.z=0;camera.pan(100,0,800);
assert.ok(camera.x<0);near(camera.z,0);
camera.yaw=Math.PI/2;camera.x=0;camera.z=0;camera.pan(100,0,800);
near(camera.x,0);assert.ok(camera.z>0);
camera.reset();camera.follow('npc_1',{x:10,z:20});
const yaw=camera.yaw,pitch=camera.pitch;
for(let i=0;i<90;i++)camera.update({x:10,z:20},1/60);
near(camera.x,10);near(camera.z,20);near(camera.distance,42);
camera.update({x:16,z:20},1/60);assert.ok(camera.x>10&&camera.x<16);
assert.equal(camera.yaw,yaw);assert.equal(camera.pitch,pitch);
camera.zoom(-400);assert.equal(camera.followId,'npc_1');assert.ok(camera.distance<42);
camera.follow('npc_2',{x:-10,z:-15});camera.update({x:-10,z:-15},1/60,true);
near(camera.x,-10);near(camera.z,-15);assert.equal(camera.followId,'npc_2');
camera.pan(1,0,800);assert.equal(camera.followId,null);
const freeX=camera.x;camera.update({x:40,z:20},1);assert.equal(camera.x,freeX);
camera.follow('npc_2',{x:0,z:0});camera.rotate(1,0);assert.equal(camera.followId,null);
camera.follow('npc_2',{x:0,z:0});camera.update(null,1/60);assert.equal(camera.followId,null);
for(let i=0;i<10;i++)camera.zoom(10000);assert.equal(camera.distance,150);
for(let i=0;i<10;i++)camera.zoom(-10000);assert.equal(camera.distance,14);
camera.reset();assert.equal(camera.distance,99);assert.equal(camera.followId,null);
assert.ok(Object.values(camera.view().position).every(Number.isFinite));
console.log('Camera checks passed: free orbit, camera-relative pan, pitch/zoom limits, moving-target follow, retarget, interruption, reduced motion, reset.');
