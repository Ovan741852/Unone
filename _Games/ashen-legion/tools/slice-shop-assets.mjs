import {writeFileSync,mkdirSync} from 'node:fs';
import {skins,slices as suffixes} from '../presentation/ui-components.mjs';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {join} from 'node:path';
import {createRequire} from 'node:module';

const root=fileURLToPath(new URL('../',import.meta.url));
const dir=join(root,'assets/formal-ui');
mkdirSync(dir,{recursive:true});
const require=createRequire(import.meta.url);
const {chromium}=require('C:/Users/liNao/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const sources=Object.keys(skins),metadata={};
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1100,height:800}});
 for(const name of sources){
  const source=pathToFileURL(join(dir,name+'.png')).href;
  await page.goto(source,{waitUntil:'load'});
  const result=await page.evaluate(({suffixes,spec,name})=>{
   const image=document.images[0];let width=image.naturalWidth,height=image.naturalHeight,ox=0,oy=0;
   if(spec.trim){
    const c=document.createElement('canvas');c.width=width;c.height=height;const ctx=c.getContext('2d');ctx.drawImage(image,0,0);
    const pixels=ctx.getImageData(0,0,width,height).data;let left=width,right=0,top=height,bottom=0;
    for(let y=0;y<height;y++)for(let x=0;x<width;x++)if(pixels[(y*width+x)*4+3]>16){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
    ox=left;oy=top;width=right-left+1;height=bottom-top+1;
   }
   const [l,t,r,b]=spec.borders;
   const x=[0,l,width-r,width],y=[0,t,height-b,height],tiles=[];
   for(let row=0;row<3;row++)for(let col=0;col<3;col++){
    const cropWidth=x[col+1]-x[col],cropHeight=y[row+1]-y[row];
    const canvas=document.createElement('canvas');canvas.width=cropWidth;canvas.height=cropHeight;
    const context=canvas.getContext('2d');context.clearRect(0,0,cropWidth,cropHeight);
    context.drawImage(image,ox+x[col],oy+y[row],cropWidth,cropHeight,0,0,cropWidth,cropHeight);
    tiles.push({name:suffixes[row*3+col],data:canvas.toDataURL('image/png').split(',')[1]});
   }
   return {width,height,ox,oy,tiles};
  },{suffixes,spec:skins[name],name});
  for(const tile of result.tiles)writeFileSync(join(dir,`${name}-${tile.name}.png`),Buffer.from(tile.data,'base64'));
  metadata[name]={width:result.width,height:result.height,trim:[result.ox,result.oy],borders:skins[name].borders};
  console.log(`${name}: ${result.width}x${result.height}, artwork-guided slices`);
 }
 writeFileSync(join(root,'presentation/ui-skin-data.mjs'),'// Generated by tools/slice-shop-assets.mjs.\nexport default '+JSON.stringify(metadata,null,2)+';\n');
}finally{await browser.close()}
