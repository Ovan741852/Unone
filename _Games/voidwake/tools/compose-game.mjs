import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
let source=await readFile(new URL('gameplay.luau',root),'utf8');
for(const name of ['audio','presentation','ui']){
 const marker=`-- @${name.toUpperCase()}@`;
 if(!source.includes(marker))throw Error(`Missing ${marker}`);
 source=source.replace(marker,await readFile(new URL(`${name}.fragment.luau`,root),'utf8'));
}
source=source.replace('--!strict','--!strict\n-- Generated by tools/compose-game.mjs from gameplay + engine API presentation fragments.');
await writeFile(new URL('main.luau',root),source);
console.log(`Composed ${fileURLToPath(new URL('main.luau',root))}`);
