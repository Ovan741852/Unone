// Revalidate current direct WebGPU executor after owned-clone intake repair.
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {resolve} from 'node:path';
const at=process.argv.indexOf('--root'),root=resolve(process.argv[at+1]);
const argv=['scripts/verify-spatial-webgpu.mjs','docs/audits/spatial-observation-profile-2026-10-23/kernel-result.json'];
const r=spawnSync(process.execPath,argv,{cwd:root,env:{...process.env,CARGO_NET_OFFLINE:'true'},encoding:'utf8',windowsHide:true,timeout:55000,maxBuffer:100*1024});
console.log(JSON.stringify({event:'kernel',argv:[process.execPath,...argv],status:r.status,error:r.error?.message,stdout:r.stdout,stderr:r.stderr}));
assert.ok(!r.error);assert.equal(r.status,0);
const report=JSON.parse(r.stdout);assert.equal(report.ok,true);
console.log(JSON.stringify({event:'task_result',complete:true,browser:report.browser,scope:'current real WebGPU differential/capacity/host-profile regression; Rust reference fixtures are generated by a selected standalone example; selected sources do not fingerprint the full compiler dependency graph; no speedup claim'}));
