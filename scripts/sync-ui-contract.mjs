// Release/check gate: Rust reads this JSON directly; JS consumers ship a
// generated module so WebViews need neither JSON modules nor a runtime fetch.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const contract=JSON.parse(fs.readFileSync(path.join(root,'crates/unone-engine/src/ui-contract.json'),'utf8'));
const source='// Generated by scripts/sync-ui-contract.mjs; do not edit.\nexport const UI_CONTRACT = Object.freeze('+JSON.stringify(contract,null,2)+');\n';
const outputs=[[path.join(root,'web/shared/ui-contract.mjs'),source]];
const pluginAt=process.argv.indexOf('--plugin');
if(pluginAt>=0){
 const plugin=path.resolve(process.argv[pluginAt+1]);
 outputs.push([path.join(plugin,'src/ui-contract.mjs'),source]);
 outputs.push([path.join(plugin,'src/ui-geometry.mjs'),fs.readFileSync(path.join(root,'web/shared/ui-geometry.mjs'),'utf8')]);
 const luaPath=path.join(plugin,'luau/unone_ui.luau');
 const lua=fs.readFileSync(luaPath,'utf8');
 const generated='-- BEGIN GENERATED UI CONTRACT\nlocal contract = {'+Object.entries(contract).map(([k,v])=>`${k}=${v}`).join(',')+'}\n-- END GENERATED UI CONTRACT';
 outputs.push([luaPath,lua.replace(/-- BEGIN GENERATED UI CONTRACT[\s\S]*?-- END GENERATED UI CONTRACT/,generated)]);
 const schema=JSON.parse(fs.readFileSync(path.join(plugin,'schemas/ui-components.schema.json'),'utf8'));
 if(schema.$defs.screen.properties.children.maxItems!==contract.host_max_nodes||schema.$defs.screen.properties.budget.properties.max_nodes.maximum!==contract.host_max_nodes)throw Error('UI_SCHEMA_DRIFT: plugin schema must use the host safety ceiling, not the default screen budget');
 const manifest=JSON.parse(fs.readFileSync(path.join(plugin,'plugin.json'),'utf8'));
 for(const tool of manifest.tools){
  const tree=tool.input_schema?.properties?.tree;
  if(tree&&(tree.properties.children.maxItems!==contract.host_max_nodes||tree.properties.budget?.properties.max_nodes.maximum!==contract.host_max_nodes))throw Error(`UI_SCHEMA_DRIFT: ${tool.name} manifest must expose the same configurable budget as the component schema`);
 }
}
for(const [file,content]of outputs){
 if(process.argv.includes('--check')){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==content)throw Error(`UI_CONTRACT_DRIFT: ${file}; run scripts/sync-ui-contract.mjs with the same --plugin argument`);}
 else fs.writeFileSync(file,content);
}
console.log(`UI contract v${contract.version}: ${outputs.length} consumers ${process.argv.includes('--check')?'verified':'generated'}`);
