"""Generate fixed neutral conformance goldens with independent CPU math, never GPU outputs."""
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
NODE = ROOT / '.toolcache/emsdk/node/24.19.0_64bit/node.exe'
reference_spec = importlib.util.spec_from_file_location('independent', ROOT / 'scripts/raster-probe-reference.py')
reference = importlib.util.module_from_spec(reference_spec)
reference_spec.loader.exec_module(reference)
source = ROOT / 'web/renderer/projected-raster-profile.js'
command = "import {pathToFileURL} from 'node:url'; const x=await import(pathToFileURL(process.argv[1])); process.stdout.write(JSON.stringify(x.rasterProfileInputs()));"
inputs = json.loads(subprocess.check_output([str(NODE), '--input-type=module', '-e', command, str(source)]))
expected = {case['id']:[{'point':p,'rgb':value['rgb'],'marker':int(bool(value['surviving_draws']))}
                       for p in case['points'] for value in [reference.pixel(case,p,inputs['images'])]] for case in inputs['cases']}
fixed = {'version':'upper-left-v1','expected':expected,'case_count':len(inputs['cases']),
         'sample_count':sum(len(rows) for rows in expected.values()),'reference':'independent top-left half-plane, perspective, depth, sRGB; no GPU-derived values'}
canonical = json.dumps({'inputs':inputs,'fixed':fixed},sort_keys=True,separators=(',',':')).encode('utf-8')
fixed['hash'] = hashlib.sha256(canonical).hexdigest()
target = ROOT / 'web/renderer/projected-raster-profile-expected.js'
target.write_text('// Generated by scripts/build-projected-raster-profile.py; fixed independent reference.\nexport const RASTER_PROFILE='+json.dumps(fixed,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({k:v for k,v in fixed.items() if k!='expected'}))
